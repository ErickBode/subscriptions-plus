// Builds src/lib/glyphs.ts: every glyph referenced by the catalog (and the extras below),
// embedded so the app works offline. Plain keys come from the simple-icons package;
// "prefix:name" keys are fetched once from the Iconify API.
// Run: node scripts/build-glyphs.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import * as si from 'simple-icons';

// Card brands for payment methods and icons used by migrated subscriptions.
const EXTRA = ['visa', 'mastercard', 'americanexpress', 'tabler:ghost-2', 'tabler:credit-card'];

const catalog = readFileSync('src/lib/catalog.ts', 'utf8');
const keys = [...new Set([...[...catalog.matchAll(/glyph: '([^']+)'/g)].map((m) => m[1]), ...EXTRA])].sort();

const bySlug = new Map(Object.values(si).filter((i) => i && i.slug).map((i) => [i.slug, i]));
const out = {};
const missing = [];

for (const key of keys.filter((k) => !k.includes(':'))) {
  const icon = bySlug.get(key);
  if (!icon) { missing.push(key); continue; }
  out[key] = { body: `<path fill="currentColor" d="${icon.path}"/>`, width: 24, height: 24 };
}

const byPrefix = {};
for (const key of keys.filter((k) => k.includes(':'))) {
  const [prefix, name] = key.split(':');
  (byPrefix[prefix] ??= []).push(name);
}
for (const [prefix, names] of Object.entries(byPrefix)) {
  const res = await fetch(`https://api.iconify.design/${prefix}.json?icons=${names.join(',')}`);
  const json = await res.json();
  for (const name of names) {
    const icon = json.icons?.[name];
    if (!icon) { missing.push(`${prefix}:${name}`); continue; }
    out[`${prefix}:${name}`] = { body: icon.body, width: icon.width ?? json.width ?? 16, height: icon.height ?? json.height ?? 16 };
  }
}

if (missing.length) {
  console.error('missing glyphs:', missing.join(', '));
  process.exit(1);
}

const lines = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
writeFileSync('src/lib/glyphs.ts', `// Generated by scripts/build-glyphs.mjs; do not edit by hand.
// Sources: simple-icons (CC0) and Iconify sets (ri, tabler, fa6-brands, mdi, game-icons).

export interface Glyph { body: string; width: number; height: number }

export const GLYPHS: Record<string, Glyph> = {
${lines.join('\n')}
};
`);
console.log(`${Object.keys(out).length} glyphs written`);
